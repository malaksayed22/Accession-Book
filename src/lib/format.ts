export function formatDate(date: Date | string | null | undefined): string {
  if (!date) return "—";
  const d = typeof date === "string" ? new Date(date) : date;
  return d.toLocaleDateString("en-CA");
}

/**
 * `YYYY-MM-DD` for an `<input type="date">`, in the viewer's zone rather than
 * UTC — otherwise an evening entry west of UTC defaults to tomorrow.
 */
export function toDateInputValue(date: Date = new Date()): string {
  const local = new Date(date.getTime() - date.getTimezoneOffset() * 60000);
  return local.toISOString().slice(0, 10);
}

export function formatDateTime(date: Date | string | null | undefined): string {
  if (!date) return "—";
  const d = typeof date === "string" ? new Date(date) : date;
  return d.toLocaleString("en-CA", {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  });
}

export function roleLabel(permissions: string | null | undefined): string {
  return permissions === "ADMIN" ? "Admin" : "Member";
}
